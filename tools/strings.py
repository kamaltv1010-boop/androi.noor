root = Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "res"


def android(text):
    text = escape(text)
    return text.replace("'", "\\'").replace('"', '\\"')


for index, folder in enumerate(["values", "values-ar", "values-fr"]):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/strings.py. -->", "<resources>"]
    for name in sorted(S):
        extra = ' formatted="true"' if "%" in S[name][index] else ""
        lines.append(f'    <string name="{name}"{extra}>{android(S[name][index])}</string>')
    lines.append("</resources>")
    out = root / folder / "strings.xml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out, len(S))
